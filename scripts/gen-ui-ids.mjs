#!/usr/bin/env node
/**
 * Generates `src/editor/ui-ids.d.ts`, the element type of every id in the editor's markup, so `svgCanvas.$id('angle')` and
 * `$req('angle')` return `se-spin-input`'s class instead of a bare `HTMLElement`.
 *
 * It reads the panels' `.html` files and the HTML templates inside the JS sources (extensions inject their panels as template
 * strings) for `<tag … id="x">`. An interpolation (`${P}-pick`) is filled in from the file's top-level string constant (`const P =
 * 'ext-blend'`), and an id that stays dynamic is skipped, as is one that two places give different tags (the lookup then returns `HTMLElement`). `npm run gen-ui-ids` rewrites the file; `tests/unit/ui-ids.test.js`
 * fails when it is stale.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const NATIVE = {
  input: 'HTMLInputElement',
  select: 'HTMLSelectElement',
  textarea: 'HTMLTextAreaElement',
  button: 'HTMLButtonElement',
  div: 'HTMLDivElement',
  span: 'HTMLSpanElement',
  img: 'HTMLImageElement',
  canvas: 'HTMLCanvasElement',
  dialog: 'HTMLDialogElement',
  label: 'HTMLLabelElement',
  ul: 'HTMLUListElement',
  li: 'HTMLLIElement',
  a: 'HTMLAnchorElement',
  form: 'HTMLFormElement',
  option: 'HTMLOptionElement',
  details: 'HTMLDetailsElement',
  p: 'HTMLParagraphElement',
  table: 'HTMLTableElement',
  tbody: 'HTMLTableSectionElement',
  tr: 'HTMLTableRowElement',
  td: 'HTMLTableCellElement',
  slot: 'HTMLSlotElement',
  style: 'HTMLStyleElement',
  h1: 'HTMLHeadingElement',
  h2: 'HTMLHeadingElement',
  h3: 'HTMLHeadingElement',
  template: 'HTMLTemplateElement',
  datalist: 'HTMLDataListElement'
}

/** The type an element of `tag` has, or `null` for a tag with no useful one (svg parts, …). */
const typeOfTag = (tag) => {
  if (NATIVE[tag]) return NATIVE[tag]
  if (tag.includes('-')) return `HTMLElementTagNameMap['${tag}']`
  return null
}

/**
 * The `id → type` map found in some markup.
 * @param {string[]} sources - file contents
 * @returns {Map<string, string>} ids whose tags agree everywhere
 */
export const idTypes = (sources) => {
  const found = new Map()
  for (const text of sources) {
    // a file's top-level string constants (`const P = 'ext-blend'`) stand in for `${P}` in the ids of its templates
    const consts = new Map([...text.matchAll(/^const (\w+) = '([^'$]*)'/gm)].map((m) => [m[1], m[2]]))
    for (const m of text.matchAll(/<([a-z][\w-]*)\b[^<>]*?\sid=["']([^"'<>]+)["']/g)) {
      const [, tag] = m
      let skip = false
      const id = m[2].replace(/\$\{(\w+)\}/g, (all, name) => {
        if (consts.has(name)) return consts.get(name)
        skip = true
        return all
      })
      if (skip || /[${}]/.test(id)) continue
      const type = typeOfTag(tag)
      if (!type) { found.set(id, null); continue }
      if (found.has(id) && found.get(id) !== type) found.set(id, null)
      else if (!found.has(id)) found.set(id, type)
    }
  }
  for (const [id, type] of found) if (!type) found.delete(id)
  return found
}

/** The `.d.ts` text for an id map. */
export const render = (map) => {
  const rows = [...map].sort(([a], [b]) => a.localeCompare(b)).map(([id, type]) => `  ${/^[A-Za-z_$][\w$]*$/.test(id) ? id : `'${id}'`}: ${type}`)
  return `/**
 * Element type of each id in the editor's markup (generated by \`npm run gen-ui-ids\`; do not edit). Merged into \`ElementIdMap\`
 * (\`packages/svgcanvas/core/dom-utils.ts\`) so \`$id\` / \`$req\` return it.
 */
interface ElementIdMap {
${rows.join('\n')}
}
`
}

const SKIP = new Set(['vendor', 'locale', 'tests', 'node_modules', 'images'])
const markupFiles = (dir) => readdirSync(dir).flatMap((name) => {
  const path = join(dir, name)
  if (SKIP.has(name)) return []
  if (statSync(path).isDirectory()) return markupFiles(path)
  return /\.(js|html)$/.test(name) && !name.endsWith('.test.js') ? [path] : []
})

export const generate = (root) => {
  const editor = join(root, 'src/editor')
  const sources = markupFiles(editor).map((f) => readFileSync(f, 'utf8'))
  return render(idTypes(sources))
}

const main = () => {
  const root = resolve(import.meta.dirname, '..')
  writeFileSync(join(root, 'src/editor/ui-ids.d.ts'), generate(root))
  console.log(`gen-ui-ids: wrote ${relative(root, join(root, 'src/editor/ui-ids.d.ts'))}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
